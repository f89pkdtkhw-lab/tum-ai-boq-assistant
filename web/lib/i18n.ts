// English is the key; German comes from DE. A missing entry falls back to the English text, so untranslated
// strings stay readable. Placeholders: "{n} items" with werte { n: 3 }.
export type Sprache = "en" | "de";

export function uebersetze(sprache: Sprache, text: string, werte?: Record<string, string | number>): string {
  const roh = sprache === "de" ? DE[text] ?? text : text;
  return werte ? roh.replace(/\{(\w+)\}/g, (_, k) => (k in werte ? String(werte[k]) : `{${k}}`)) : roh;
}

